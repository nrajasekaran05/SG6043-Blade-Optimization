def class_func(x):
    return np.sqrt(x) * (1 - x)


def CST_chebyshev_TE(x, *a):
    """
    CST + Chebyshev with trailing edge thickness included.
    Last coefficient is treated as TE offset.
    """
    *cheb_coeffs, te_offset = a  # split last value
    xi = 2 * x - 1
    T = chebvander(xi, len(cheb_coeffs)-1)
    shape = T @ np.array(cheb_coeffs)
    y = class_func(x) * shape
    return y + te_offset * x  # Linearly increasing TE offset


