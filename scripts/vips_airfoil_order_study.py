x_dense = np.linspace(0, 1, 200)

def class_func(x):
    return (np.sqrt(x) * (1 - x))**0.5

def CST_chebyshev_TE(x, *a):
    *cheb_coeffs, te_offset = a
    xi = 2 * x - 1
    T = chebvander(xi, len(cheb_coeffs) - 1)
    shape = T @ np.array(cheb_coeffs)
    y = class_func(x) * shape
    return y + te_offset * x

# -------- Error function --------
def compute_mse(y_true, y_pred):
    return np.mean((y_true - y_pred)**2)

# -------- Main Loop for each order --------
orders = [5, 6, 7, 8,9]
errors_upper = []
errors_lower = []
fits_upper = []
fits_lower = []

for n in orders:
    p0 = np.zeros(n + 1)  # n chebyshev + 1 for TE offset
    # Fit upper
    popt_u, _ = curve_fit(lambda x, *a: CST_chebyshev_TE(x, *a), x_upper, y_upper, p0=p0)
    fit_u = CST_chebyshev_TE(x_upper, *popt_u)
    mse_u = compute_mse(y_upper, fit_u)

    # Fit lower
    popt_l, _ = curve_fit(lambda x, *a: CST_chebyshev_TE(x, *a), x_lower, y_lower, p0=p0)
    fit_l = CST_chebyshev_TE(x_lower, *popt_l)
    mse_l = compute_mse(y_lower, fit_l)

    errors_upper.append(mse_u)
    errors_lower.append(mse_l)
    fits_upper.append(CST_chebyshev_TE(x_dense, *popt_u))
    fits_lower.append(CST_chebyshev_TE(x_dense, *popt_l))

